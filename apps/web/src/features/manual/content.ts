export function articleForPath(pathname: string): ManualArticle | undefined {
  const parts = pathname.replace(/\/$/, "").split("/");
  // /new と動的な詳細の両方に一致する場合は固定のパスを優先する。
  return manualArticles
    .flatMap((article) => article.paths.map((path) => ({ article, path })))
    .sort((a, b) => a.path.split("$").length - b.path.split("$").length)
    .find(({ path }) => {
      const expected = path.replace(/\/$/, "").split("/");
      return (
        expected.length === parts.length &&
        expected.every((part, i) => part.startsWith("$") || part === parts[i])
      );
    })?.article;
}

export function searchManual(query: string): ManualArticle[] {
  const words = query.normalize("NFKC").toLocaleLowerCase("ja").trim().split(/\s+/).filter(Boolean);
  return manualArticles.filter((article) => {
    const text = [
      article.title,
      article.category,
      article.summary,
      article.start,
      article.prerequisite,
      ...article.steps.flat(),
      ...article.cautions,
      ...article.faq.flat(),
    ]
      .join(" ")
      .normalize("NFKC")
      .toLocaleLowerCase("ja");
    return words.every((word) => text.includes(word));
  });
}

export function manualImages(article: ManualArticle): { image: string; caption: string }[] {
  return [{ image: article.image, caption: article.caption }, ...(article.stepImages ?? [])];
}
